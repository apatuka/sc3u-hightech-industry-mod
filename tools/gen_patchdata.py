"""Generate src/PatchData.cs for the two distributable patchers from the tested Python patch definitions.

  python gen_patchdata.py rci|ht <output PatchData.cs>
rci = SC3U Full RCI Patch, ht = SC3U High-Tech Industry (needs keystone-engine, capstone, pefile)
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mod_rci_dll, mod_simgeom_dll

SIMRCI = dict(file="SIMRCI.DLL", size=393216, stamp=0x38FD559F, vsize=0x49162,
              sha="41378d72f09f89980b19e210787225950e7f6f477928f62d960ce1f811395f53")
SIMGEOM = dict(file="SIMGEOM.DLL", size=221184, stamp=0x38FD54B7, vsize=0x27452,
               sha="17a76e833412108298e0f88e6af49c56280837584d74ce0b1b93da03bdcdfaba")
HEADER = "// GENERATED by tools/gen_patchdata.py from the tested patch definitions - do not edit by hand.\n"


def caves(all_blocks):
    """[start, end) of every code cave of every SC3U mod in this DLL (blocks whose original bytes are all zero)."""
    r = sorted((b[0], b[0] + len(b[2])) for b in all_blocks if not any(b[1]) and b[0] < 0x10050000)
    return ", ".join("0x%08X, 0x%08X" % c for c in r)


def dll(name, info, blocks, all_blocks):
    out = ['        public static readonly DllPatch %s = new DllPatch("%s", %d, 0x%08X, 0x%X, "%s",'
           % (name, info["file"], info["size"], info["stamp"], info["vsize"], info["sha"]),
           "            // code caves of all SC3U mods in this DLL (lets uninstall shrink .text VirtualSize exactly)",
           "            new uint[] { %s }," % caves(all_blocks),
           "            new Block[] {"]
    for b in blocks:
        va, old, new, desc = b[:4]
        out.append('            new Block(0x%08X, "%s", "%s"), // %s' % (va, old.hex(), new.hex(), desc))
    out.append("        });")
    return "\n".join(out)


def write(path, body):
    with open(path, "w", newline="\r\n") as f:
        f.write(HEADER + "namespace SC3UMod\n{\n    static class PatchData\n    {\n" + body + "\n    }\n}\n")
    print("wrote", path)


def main(which, out):
    sets = dict(mod_rci_dll.SETS)
    rci_all = sets["rci"] + sets["hightech_map"] + sets["hightech_zone"]
    geom = dict(mod_simgeom_dll.SETS)["hightech_query"]
    if which == "rci":
        write(out, dll("SimRci", SIMRCI, sets["rci"], rci_all))
    elif which == "ht":
        write(out, dll("SimRci", SIMRCI, sets["hightech_map"] + sets["hightech_zone"], rci_all) + "\n\n" +
              dll("SimGeom", SIMGEOM, geom, geom))
    else:
        sys.exit("usage: gen_patchdata.py rci|ht <output PatchData.cs>")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: gen_patchdata.py rci|ht <output PatchData.cs>")
    main(sys.argv[1], sys.argv[2])
